def f(g, s, e, v=None):
    if v is None: v = []     # если список посещённых не передан — создаём пустой
    v = v + [s]              # добавляем текущий узел в посещённые
    if s == e: return v, 0   # если дошли до конца — возвращаем путь и вес 0

    best = None              # лучший найденный путь (пока не найден)
    for n, w in g.get(s, []):   # перебираем соседей текущего узла (n=сосед, w=вес)
        if n not in v:           # если сосед ещё не посещён —
            r = f(g, n, e, v)    # рекурсивно ищем путь от соседа до конца
            if r:                # если путь найден —
                p, d = r         # p=путь, d=суммарный вес от соседа до конца
                d += w           # прибавляем вес текущего ребра
                if not best or d < best[1]:  # если это лучший путь из найденных —
                    best = (p, d)            # запоминаем его
    return best              # возвращаем лучший путь

g = {
    'A': [('B', 1), ('C', 4)],  # из A можно попасть в B(вес 1) и C(вес 4)
    'B': [('C', 2), ('D', 5)],  # из B можно попасть в C(вес 2) и D(вес 5)
    'C': [('D', 1)],            # из C можно попасть в D(вес 1)
    'D': []                     # D — конечный узел, выходов нет
}

print(f(g, 'A', 'D'))  # ищем кратчайший путь из A в D
                        # → (['A', 'B', 'C', 'D'], 4)
